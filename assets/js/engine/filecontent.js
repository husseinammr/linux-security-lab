/**
 * engine/filecontent.js  (Linux Security Lab)
 * Real text content for the few files whose contents an investigator reads. In the original lab a file only had a
 * one-line description; here /etc/passwd, /etc/group, /etc/shadow, the hostname/DNS files and the two logs
 * (/var/log/auth.log, /var/log/syslog) produce believable lines, and a scenario can attach its own `content`
 * (an array of lines) to any node it builds. Permissions are NOT decided here: the terminal checks access first.
 * Everything is synthetic — the "hashes" in /etc/shadow are obvious placeholders, not real password hashes.
 */
import { USERS, GROUP_IDS, groupMembers } from "./users.js";
import { SYSTEM_INFO, LOG_EVENTS, formatLogLine } from "./sysinfo.js";

const SHELLS = { root: "/bin/bash", user: "/bin/bash", alice: "/bin/bash", deployer: "/bin/bash", monitoring: "/usr/sbin/nologin", "www-data": "/usr/sbin/nologin" };
const GECOS = { root: "root", user: "Lab User", alice: "Alice", deployer: "App deployer", monitoring: "Monitoring agent", "www-data": "www-data" };

export function passwdLines() {
  return Object.entries(USERS).map(([n, u]) => `${n}:x:${u.uid}:${GROUP_IDS[u.groups[0]]}:${GECOS[n] || n}:${u.home}:${SHELLS[n] || "/bin/bash"}`);
}
export function groupLines() {
  return Object.entries(GROUP_IDS).map(([g, id]) => `${g}:x:${id}:${groupMembers(g).join(",")}`);
}
export function shadowLines() {
  return Object.entries(USERS).map(([n, u]) => {
    const hash = n === "monitoring" || n === "www-data" ? "*" : `$6$SIMULATED$placeholder-not-a-real-hash-${n}`;
    return `${n}:${u.locked ? "!" : ""}${hash}:20370:0:99999:7:::`;
  });
}

const STATIC = {
  "/etc/hostname": () => [SYSTEM_INFO.hostname],
  "/etc/hosts": () => ["127.0.0.1 localhost", `127.0.1.1 ${SYSTEM_INFO.hostname}`, "::1 localhost ip6-localhost ip6-loopback"],
  "/etc/resolv.conf": () => ["# Generated by systemd-resolved (simulated)", "nameserver 10.0.2.3", "search localdomain"],
  "/etc/passwd": passwdLines,
  "/etc/group": groupLines,
  "/etc/shadow": shadowLines,
  "/var/log/auth.log": () => LOG_EVENTS.filter((e) => e.source === "auth").map((e) => formatLogLine(e)),
  "/var/log/syslog": () => LOG_EVENTS.filter((e) => e.source !== "auth").map((e) => formatLogLine(e)),
};

/** Lines of text for a node, or null when the file only has a description. */
export function contentFor(node) {
  if (!node || node.isDir) return null;
  if (Array.isArray(node.content)) return node.content;
  const gen = STATIC[node.path];
  return gen ? gen() : null;
}
